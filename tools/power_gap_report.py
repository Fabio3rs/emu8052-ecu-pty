"""Power-gap decomposition tables from the investigation CSVs (no hand-typed numbers).
Reads docs/dyno/investigation/{matrix,isolated_amb20,isolated_amb36}.csv and writes decomposition.md.
LLM-written (Claude)."""
import csv
from pathlib import Path

D = Path(__file__).resolve().parent.parent / "docs/dyno/investigation"
m = {}
for r in csv.DictReader(open(D / "matrix_pre_fix.csv")):
    m[(r["experiment"], int(float(r["target_rpm"])))] = r
iso = {t: {int(float(r["rpm"])): r for r in csv.DictReader(open(D / f"isolated_amb{t}.csv"))} for t in (20, 36)}
rpms = [1500, 3000, 4500, 6000]
f = lambda e, n, k: float(m[(e, n)][k])
out = ["<!-- generated by tools/power_gap_report.py; do not edit -->", ""]

out += ["### Tabela 1 - isolada (sem ROM) contra ROM, potencia de eixo", "",
        "| RPM | isolada 20 C [kW] | isolada 36 C [kW] | ROM original [kW] | deficit total [kW] | deficit [%] |",
        "|---:|---:|---:|---:|---:|---:|"]
for n in rpms:
    a, b, e = float(iso[20][n]["power_kw"]), float(iso[36][n]["power_kw"]), f("E0_original", n, "shaft_power_kw")
    out.append(f"| {n} | {a:.2f} | {b:.2f} | {e:.2f} | {a-e:.2f} | {100*(a-e)/a:.1f} |")

out += ["", "### Tabela 2 - decomposicao por intervencao isolada a partir da ROM original (kW)", "",
        "Cada coluna e o ganho de potencia ao aplicar UMA intervencao sobre a ROM original. "
        "'Residual' = deficit total - soma das parcelas (interacoes e efeitos nao isolados).", "",
        "| RPM | ar de admissao 20->36 C | bomba x0,04 (hip.) | alternador off | forca centelha saturada | avanco = MBT | soma | residual |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|"]
for n in rpms:
    e = f("E0_original", n, "shaft_power_kw")
    air = float(iso[20][n]["power_kw"]) - float(iso[36][n]["power_kw"])
    parts = [air, f("A4_pump_x0.04", n, "shaft_power_kw") - e, f("A1_alt_off", n, "shaft_power_kw") - e,
             f("S1_strength_sat", n, "shaft_power_kw") - e, f("I1_mbt", n, "shaft_power_kw") - e]
    gap = float(iso[20][n]["power_kw"]) - e
    out.append(f"| {n} | " + " | ".join(f"{p:.2f}" for p in parts) + f" | {sum(parts):.2f} | {gap-sum(parts):.2f} |")

out += ["", "### Tabela 3 - fechamento: ROM com bomba x0,04 + forca saturada + avanco MBT contra isolada a 36 C", "",
        "| RPM | ROM combinada [kW] | isolada 36 C [kW] | razao |", "|---:|---:|---:|---:|"]
for n in rpms:
    c, b = f("C2_pump04_sat_mbt", n, "shaft_power_kw"), float(iso[36][n]["power_kw"])
    out.append(f"| {n} | {c:.2f} | {b:.2f} | {100*c/b:.1f} % |")

out += ["", "### Tabela 4 - acessorios (torque medio no virabrequim, N.m)", "",
        "| RPM | modelo atual | alternador off | bomba off | ambos off | bomba x0,04 |", "|---:|---:|---:|---:|---:|---:|"]
for n in rpms:
    out.append(f"| {n} | " + " | ".join(f"{f(e, n, 'accessory_nm'):.2f}" for e in
               ("E0_original", "A1_alt_off", "A2_pump_off", "A3_acc_off", "A4_pump_x0.04")) + " |")

out += ["", "### Tabela 5 - estado da ROM e mistura (original)", "",
        "| RPM | avanco ROM [graus] | MBT planta [graus] | forca centelha media | eta_i | VE amb. | ar [mg/cil] | lambda | IRAM66 TPS1 | XRAM F8E8 |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
for n in rpms:
    g = lambda k: m[("E0_original", n)][k]
    out.append(f"| {n} | {float(g('adv_mean_deg')):.2f} | {float(g('mbt_mean_deg')):.2f} | {float(g('spark_strength_mean')):.3f} | "
               f"{float(g('eta_i_mean')):.4f} | {float(g('ve_ambient')):.4f} | {float(g('air_mg_cyl')):.1f} | {float(g('lambda')):.4f} | {g('iram66_tps1')} | {g('xram_f8e8')} |")

out += ["", "### Tabela 6 - historico (tempo de marcha lenta livre antes do degrau de pedal)", "",
        "| RPM | 6 M ticks [kW] | 12 M (padrao) [kW] | 24 M [kW] | avanco 6M / 12M / 24M [graus] | XRAM F8E8 6M / 12M / 24M |", "|---:|---:|---:|---:|---:|---:|"]
for n in rpms:
    es = ("H1_settle_6M", "E0_original", "H2_settle_24M")
    out.append(f"| {n} | " + " | ".join(f"{f(e, n, 'shaft_power_kw'):.2f}" for e in es) + " | " +
               " / ".join(f"{f(e, n, 'adv_mean_deg'):.2f}" for e in es) + " | " +
               " / ".join(m[(e, n)]["xram_f8e8"] for e in es) + " |")

out += ["", "### Tabela 7 - sensibilidade ao avanco (retardo a partir do MBT, kW)", "",
        "| RPM | original | MBT | MBT-5 | MBT-10 |", "|---:|---:|---:|---:|---:|"]
for n in rpms:
    out.append(f"| {n} | " + " | ".join(f"{f(e, n, 'shaft_power_kw'):.2f}" for e in
               ("E0_original", "I1_mbt", "I2_mbt-5", "I3_mbt-10")) + " |")
(D / "decomposition_pre_fix.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
