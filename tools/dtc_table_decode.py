"""Decode the ROM DTC record table: entry = 6E27h + 3*R3 + R7, R7 in {0,3,6,9} chosen by 43BDh..4431h
(R3 >= 12 -> 9; R3 = 11 -> 6 or 9; R3 = 9,10 -> 0/3/6; R3 <= 8 -> 0). Validates the rule against the DTCs the ROM
actually transmits on the K-line (tests/test_physical_kline.py, tests/test_ntc_dtc.py). LLM-written (Claude)."""
import sys
from pathlib import Path
rom = Path(sys.argv[1]).read_bytes()
out = Path(sys.argv[2])
def rec(a): return rom[a] | rom[a + 1] << 8, rom[a + 2]
rows = ["<!-- generated by tools/dtc_table_decode.py -->", "",
        "| grupo R3 | bit XRAM | R7 (bytes) | entrada | DTC / status |", "|---:|---|---:|---|---|"]
for r3 in range(1, 25):
    byte = 0x4E + (r3 - 1) // 8; bit = (r3 - 1) % 8
    r7s = [0] if r3 <= 8 else ([0, 3, 6] if r3 in (9, 10) else ([6, 9] if r3 == 11 else [9]))
    for r7 in r7s:
        a = 0x6E27 + 3 * r3 + r7
        code, st = rec(a)
        rows.append(f"| {r3} | F8{byte:02X}.{bit} | {r7} | {a:04X} | {code:04X}/{st:02X} |")
checks = [("ECT aberto (ADC3 5 V)", 12, 9, 0x0A02, 0x1E), ("ECT em curto (0 V)", 13, 9, 0x0A02, 0x1D),
          ("ar aberto (ADC2 5 V)", 15, 9, 0x0B02, 0x1E), ("ar em curto (0 V)", 16, 9, 0x0B02, 0x1D),
          ("TPS2 alto (F84F.2)", 11, 9, 0x0602, 0x1E), ("TPS1 alto (F84E.3)", 4, 0, 0x1A01, 0x1B)]
rows += ["", "Validacao contra os DTC transmitidos pela ROM na K-line:", "", "| caso | R3 | R7 | decodificado | transmitido | confere |", "|---|---:|---:|---|---|---|"]
for name, r3, r7, code, st in checks:
    c, s = rec(0x6E27 + 3 * r3 + r7)
    rows.append(f"| {name} | {r3} | {r7} | {c:04X}/{s:02X} | {code:04X}/{st:02X} | {'sim' if (c, s) == (code, st) else 'NAO'} |")
out.write_text("\n".join(rows) + "\n")
print("\n".join(rows[-9:]))
