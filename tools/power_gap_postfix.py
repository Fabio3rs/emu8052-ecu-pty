"""Post-fix comparison: ROM (default after the pump and spark-torque corrections) vs the isolated plant. LLM-written (Claude)."""
import csv
from pathlib import Path
D = Path(__file__).resolve().parent.parent / "docs/dyno"
rom = {int(float(r["target_rpm"])): r for r in csv.DictReader(open(D / "rom/sweep_tdc120.csv"))}
iso = {int(float(r["rpm"])): r for r in csv.DictReader(open(D / "investigation/isolated_amb20.csv"))}
pre = {int(float(r["target_rpm"])): r for r in csv.DictReader(open(D / "investigation/pre_fix_sweep_tdc120.csv"))}
o = ["<!-- generated by tools/power_gap_postfix.py -->", "",
     "| RPM | isolada 20 C [kW] | ROM antes da correcao [kW] | ROM apos a correcao [kW] | deficit antes [%] | deficit apos [%] | torque de eixo apos [N.m] | acessorios apos [N.m] |",
     "|---:|---:|---:|---:|---:|---:|---:|---:|"]
for n in (1500, 3000, 4500, 6000):
    a = float(iso[n]["power_kw"]); b = float(pre[n]["shaft_power_kw"]); c = float(rom[n]["shaft_power_kw"])
    o.append(f"| {n} | {a:.2f} | {b:.2f} | {c:.2f} | {100*(a-b)/a:.1f} | {100*(a-c)/a:.1f} | {float(rom[n]['shaft_torque_nm']):.1f} | {float(rom[n]['accessory_nm']):.2f} |")
o += ["", "Varredura completa da ROM apos a correcao (PMS 120 graus):", "", "| RPM | potencia [kW] | torque [N.m] | avanco [graus] | lambda | estado |", "|---:|---:|---:|---:|---:|---|"]
for n in sorted(rom):
    r = rom[n]
    o.append(f"| {n} | {float(r['shaft_power_kw']):.2f} | {float(r['shaft_torque_nm']):.1f} | {float(r['adv_mean_deg']):.2f} | {float(r['lambda']):.4f} | {r['state']} |")
(D / "investigation/postfix.md").write_text("\n".join(o) + "\n")
print("\n".join(o))
