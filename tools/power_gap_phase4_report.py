"""Phase-4 tables from docs/dyno/investigation/phase4.csv and ntc_fault_probe.json. LLM-written (Claude)."""
import csv, json
from pathlib import Path
D = Path(__file__).resolve().parent.parent / "docs/dyno/investigation"
rows = list(csv.DictReader(open(D / "phase4.csv")))
g = lambda grp: [r for r in rows if r["group"] == grp]
o = ["<!-- generated by tools/power_gap_phase4_report.py -->", ""]
f = lambda r, k, n=2: f"{float(r[k]):.{n}f}"

o += ["### Tabela P1 - abertura de pedal (fracao do curso 40,27 mm = 90 graus), freio mantendo a rotacao", "",
      "| RPM | pedal | borboleta [rad] | IRAM 60h (TPS2) | IRAM 66h (TPS1) | potencia [kW] | avanco [graus] | lambda | injecao [mg] |",
      "|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
for r in g("pedal"):
    if r["state"] == "ACCEPTED":
        o.append(f"| {int(float(r['target_rpm']))} | {r['label'].split('=')[1]} | {f(r,'throttle_rad',3)} | {r['iram60_tps2']} | {r['iram66_tps1']} | "
                 f"{f(r,'shaft_power_kw')} | {f(r,'adv_mean_deg')} | {f(r,'lambda',4)} | {f(r,'inj_mass_mg',0)} |")
    else:
        o.append(f"| {int(float(r['target_rpm']))} | {r['label'].split('=')[1]} | - | - | - | {r['state']}:{r['reason']} | - | - | - |")

o += ["", "### Tabela P2 - contrafactual: ADC0 (IRAM 60h, TPS trilha 2) forcado a 5 V a partir do degrau de pedal", "",
      "| RPM | IRAM 60h orig. | IRAM 6Dh orig. | avanco orig. | potencia orig. | IRAM 60h forcado | IRAM 6Dh forcado | avanco forcado | potencia forcada | variacao avanco | variacao potencia |",
      "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
base = {r["target_rpm"]: r for r in g("tps2_forced_base")}
for r in g("tps2_forced"):
    b = base[r["target_rpm"]]
    o.append(f"| {int(float(r['target_rpm']))} | {b['iram60_tps2']} | {b['iram6d']} | {f(b,'adv_mean_deg')} | {f(b,'shaft_power_kw')} | "
             f"{r['iram60_tps2']} | {r['iram6d']} | {f(r,'adv_mean_deg')} | {f(r,'shaft_power_kw')} | "
             f"{float(r['adv_mean_deg'])-float(b['adv_mean_deg']):+.2f} | {float(r['shaft_power_kw'])-float(b['shaft_power_kw']):+.2f} |")

o += ["", "### Tabela P3 - estado termico (temperatura da agua inicial)", "",
      "| RPM | agua [C] | resultado | potencia [kW] | avanco [graus] | lambda |", "|---:|---:|---|---:|---:|---:|"]
for r in g("coolant"):
    ok = r["state"] == "ACCEPTED"
    o.append(f"| {int(float(r['target_rpm']))} | {r['label'].split('=')[1]} | {r['state']}{'' if ok else ':' + r['reason']} | "
             f"{f(r,'shaft_power_kw') if ok else '-'} | {f(r,'adv_mean_deg') if ok else '-'} | {f(r,'lambda',4) if ok else '-'} |")

o += ["", "### Tabela P4 - sonda lambda mantida (ADC5), a partir de 2 M ticks", "",
      "| RPM | ADC5 | potencia [kW] | avanco [graus] | lambda dos cilindros |", "|---:|---|---:|---:|---:|"]
for r in g("lambda_forced"):
    o.append(f"| {int(float(r['target_rpm']))} | {r['label'].split('=')[1]} | {f(r,'shaft_power_kw')} | {f(r,'adv_mean_deg')} | {f(r,'lambda',4)} |")

o += ["", "### Tabela P5 - reinicios mornos encadeados (XRAM retida F800h-FBFFh salva e recarregada, POF=0)", "",
      "| passo | RPM | potencia [kW] | avanco [graus] | lambda | XRAM F8E8 |", "|---|---:|---:|---:|---:|---:|"]
for r in g("warm_chain"):
    o.append(f"| {r['label']} | {int(float(r['target_rpm']))} | {f(r,'shaft_power_kw')} | {f(r,'adv_mean_deg')} | {f(r,'lambda',4)} | {r['xram_f8e8']} |")

ntc = json.load(open(D / "ntc_fault_probe.json"))
o += ["", "### Tabela P6 - NTC forcado (a partir de 8 M ticks): IRAM 62h/63h e bits de falha XRAM 4Eh-50h", "",
      "Os bits sao reais (lidos da XRAM retida). A coluna de DTC e a decodificacao ingenua da tabela 6E27h por indice de bit e "
      "esta **incorreta** para os bits de F84F (ver secao de sensores): o teste `PhysicalDiagnostics.NtcSensorIdentity` usa o DTC "
      "realmente transmitido pela ROM na K-line.", "",
      "| caso | IRAM 62h | IRAM 63h | bits de falha |", "|---|---:|---:|---|"]
for r in ntc:
    o.append(f"| {r['case']} | {r['ram62']} | {r['ram63']} | {', '.join(x.split('->')[0] for x in r['faults']) or '-'} |")
sw = json.load(open(D / "ntc_swap_idle.json"))
o += ["", "### Tabela P7 - troca ADC2 <-> ADC3 (`--exp swap_ntc=1`): marcha lenta livre, 60 M ticks, ultimos 20 intervalos", "",
      "| caso | RPM medio | RPM min / max | IRAM 62h | IRAM 63h | agua [C] | ar [C] | avanco [graus] | bits de falha F84E-50 |", "|---|---:|---|---:|---:|---:|---:|---:|---|"]
for r in sw:
    o.append(f"| {r['case']} | {r['rpm_mean']} | {r['rpm_min']} / {r['rpm_max']} | {r['ram62']} | {r['ram63']} | {r['coolant_c']:.1f} | {r['iat_c']:.1f} | {r['spark']} | {r['fault_bits']} |")
pts = list(csv.DictReader(open(D / "ntc_swap_points.csv")))
o += ["", "### Tabela P8 - troca ADC2 <-> ADC3: pontos de plena carga", "",
      "| RPM | caso | resultado | potencia [kW] | avanco [graus] | lambda |", "|---:|---|---|---:|---:|---:|"]
for r in pts:
    ok = r["state"] == "ACCEPTED"
    o.append(f"| {int(float(r['target_rpm']))} | {r['case']} | {r['state']} | {f(r,'shaft_power_kw') if ok else '-'} | {f(r,'adv_mean_deg') if ok else '-'} | {f(r,'lambda',4) if ok else '-'} |")
sweep = list(csv.DictReader(open(D / "ntc_idle_sweep.csv")))
step = list(csv.DictReader(open(D / "ntc_idle_sweep_step10M.csv")))
o += ["", "### Tabela P9 - marcha lenta contra tensao forcada em um NTC por vez (aplicada desde a partida; medido em 36-48 M ticks)", "",
      "| canal | tensao [V] | IRAM 62h | IRAM 63h | RPM | combustivel [g/s] | avanco [graus] | lambda dos cilindros |", "|---|---:|---:|---:|---:|---:|---:|---:|"]
names = {"none": "referencia", "ect": "ADC3 (agua)", "air": "ADC2 (ar)"}
for r in sweep:
    o.append(f"| {names[r['channel']]} | {r['volts'] if r['channel']!='none' else '-'} | {r['ram62']} | {r['ram63']} | {r['rpm']} | {r['fuel_g_s']} | {r['spark_deg']} | {r['lambda_cyl']} |")
o += ["", "### Tabela P10 - o mesmo, mas em degrau a 10 M ticks (a ROM rejeita o salto na agua)", "",
      "| canal | tensao [V] | IRAM 62h | IRAM 63h | RPM |", "|---|---:|---:|---:|---:|"]
for r in step:
    if r['channel'] != 'none':
        o.append(f"| {names[r['channel']]} | {r['volts']} | {r['ram62']} | {r['ram63']} | {r['rpm']} |")
(D / "phase4.md").write_text("\n".join(o) + "\n")
print("\n".join(o))
